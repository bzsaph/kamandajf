    const originals = new Map();
    let current = 'en';

    function detect() {
        const fromUrl = new URLSearchParams(location.search).get('lang');
        if (fromUrl && LANGS[fromUrl]) return fromUrl;
        try {
            const saved = localStorage.getItem('jf-lang');
            if (saved && LANGS[saved]) return saved;
        } catch (e) { /* storage unavailable */ }
        return 'en';
    }

    function t(text) {
        return (current !== 'en' && UI[current] && UI[current][text]) || text;
    }

    function apply(lang) {
        if (!LANGS[lang]) lang = 'en';
        current = lang;
        document.documentElement.lang = lang === 'rw' ? 'rw' : lang;

        document.querySelectorAll('[data-i18n]').forEach(el => {
            if (!originals.has(el)) originals.set(el, el.innerHTML);
            const key = el.dataset.i18n;
            el.innerHTML = (lang !== 'en' && PAGE[lang][key]) || originals.get(el);
        });

        const meta = document.querySelector('meta[name="description"]');
        if (!originals.has('title')) {
            originals.set('title', document.title);
            originals.set('desc', meta ? meta.content : '');
        }
        document.title = lang === 'en' ? originals.get('title') : UI[lang].__title;
        if (meta) meta.content = lang === 'en' ? originals.get('desc') : UI[lang].__desc;

        document.querySelectorAll('.lang-current').forEach(el => { el.textContent = LANGS[lang]; });
        document.querySelectorAll('[data-lang]').forEach(el => el.classList.toggle('active', el.dataset.lang === lang));

        try { localStorage.setItem('jf-lang', lang); } catch (e) { /* storage unavailable */ }
        document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
    }

    window.I18N = { t, apply, get lang() { return current; } };

    document.addEventListener('DOMContentLoaded', () => {
        document.querySelectorAll('[data-lang]').forEach(btn => {
            btn.addEventListener('click', e => {
                e.preventDefault();
                apply(btn.dataset.lang);
            });
        });
        apply(detect());
    });
